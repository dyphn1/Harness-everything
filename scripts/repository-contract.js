#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const ACTION_MINIMUMS = Object.freeze({ checkout: 7, setupNode: 7 });
const MINIMUM_SUPPORTED_NODE_FLOOR = 22;

function read(root, rel) {
  return fs.readFileSync(path.join(root, rel), 'utf8');
}

function readJson(root, rel) {
  return JSON.parse(read(root, rel));
}

function parseMinimumNode(engine) {
  const match = String(engine || '').match(/>=\s*v?(\d+)/);
  return match ? Number(match[1]) : null;
}

function parseMajor(text) {
  const match = String(text || '').trim().match(/^v?(\d+)/);
  return match ? Number(match[1]) : null;
}

function uniqSorted(values) {
  return [...new Set(values.filter(Number.isInteger))].sort((a, b) => a - b);
}

function extractMajors(text, action) {
  const escaped = action.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const re = new RegExp(`uses:\\s*${escaped}@v(\\d+)`, 'g');
  const out = [];
  let match;
  while ((match = re.exec(text))) out.push(Number(match[1]));
  return uniqSorted(out);
}

function extractNodeVersions(text) {
  const out = [];
  const re = /node-version:\s*["']?(\d+)(?:\.\d+)?["']?/g;
  let match;
  while ((match = re.exec(text))) out.push(Number(match[1]));
  return uniqSorted(out);
}

function extractQualityGates(text) {
  const gates = [];
  if (/\bnpm\s+test\b/.test(text)) gates.push('test');
  const re = /\bnpm\s+run\s+([A-Za-z0-9:_-]+)/g;
  let match;
  while ((match = re.exec(text))) gates.push(match[1]);
  return [...new Set(gates)];
}

function listWorkflowFiles(root) {
  const dir = path.join(root, '.github', 'workflows');
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir)
    .filter(name => /\.ya?ml$/i.test(name))
    .sort();
}

function parseWorkflow(root, file) {
  const rel = path.posix.join('.github/workflows', file);
  const text = read(root, rel);
  return {
    file,
    nodeVersions: extractNodeVersions(text),
    checkoutMajors: extractMajors(text, 'actions/checkout'),
    setupNodeMajors: extractMajors(text, 'actions/setup-node'),
    scheduled: /^\s*schedule:\s*$/m.test(text),
    workflowDispatch: /^\s*workflow_dispatch:\s*$/m.test(text),
    workflowCall: /^\s*workflow_call:\s*$/m.test(text),
    qualityGates: extractQualityGates(text),
  };
}

function collectContract(root = ROOT) {
  const pkg = readJson(root, 'package.json');
  const nvmPath = path.join(root, '.nvmrc');
  const primaryNode = fs.existsSync(nvmPath) ? parseMajor(read(root, '.nvmrc')) : null;
  const dockerText = read(root, 'Dockerfile');
  const dockerMatch = dockerText.match(/^FROM\s+node:(\d+)(?:[^\s]*)/m);
  const workflows = listWorkflowFiles(root).map(file => parseWorkflow(root, file));
  const ci = workflows.find(workflow => workflow.file === 'ci.yml' || workflow.file === 'ci.yaml');
  const behavioral = workflows.find(workflow => /^behavioral-evals\.ya?ml$/.test(workflow.file));
  const release = workflows.find(workflow => /^release\.ya?ml$/.test(workflow.file));

  return {
    runtime: {
      packageEngine: pkg.engines?.node || null,
      minimumNode: parseMinimumNode(pkg.engines?.node),
      primaryNode,
      dockerNode: dockerMatch ? Number(dockerMatch[1]) : null,
    },
    githubActions: {
      checkoutMajors: uniqSorted(workflows.flatMap(workflow => workflow.checkoutMajors)),
      setupNodeMajors: uniqSorted(workflows.flatMap(workflow => workflow.setupNodeMajors)),
    },
    workflows: Object.fromEntries(workflows.map(workflow => [workflow.file, workflow])),
    ci: ci || null,
    behavioralEvals: behavioral || null,
    release: release || null,
  };
}

function renderContractMarkdown(contract) {
  const runtime = contract.runtime;
  const actionList = values => values.length ? values.map(v => `v${v}`).join(', ') : 'not used';
  const rows = Object.values(contract.workflows).map(workflow => {
    const nodes = workflow.nodeVersions.length ? workflow.nodeVersions.map(String).join(', ') : 'n/a';
    const trigger = [workflow.scheduled && 'schedule', workflow.workflowDispatch && 'workflow_dispatch', workflow.workflowCall && 'workflow_call'].filter(Boolean).join(', ') || 'push/pull request or other';
    const gates = workflow.qualityGates.length ? workflow.qualityGates.map(g => `\`${g}\``).join(', ') : 'n/a';
    return `| \`${workflow.file}\` | ${nodes} | ${trigger} | ${gates} |`;
  }).join('\n');

  return `<!-- GENERATED by scripts/repository-contract.js. Run \`npm run docs:sync\` after workflow/runtime changes. -->\n# Repository runtime and workflow contract\n\nThis page is generated from checked-in runtime and workflow sources. Do not edit it by hand. Historical audit/evidence documents are intentionally outside this current-state contract.\n\n## Runtime\n\n- Minimum supported Node.js: **${runtime.minimumNode}** (from \`package.json#engines.node\`: \`${runtime.packageEngine}\`)\n- Primary development/CI Node.js: **${runtime.primaryNode}** (from \`.nvmrc\`)\n- Docker verification Node.js: **${runtime.dockerNode}** (from \`Dockerfile\`)\n\n## GitHub Actions runtime majors\n\n- \`actions/checkout\`: ${actionList(contract.githubActions.checkoutMajors)}\n- \`actions/setup-node\`: ${actionList(contract.githubActions.setupNodeMajors)}\n\n## Active workflows\n\n| Workflow | Node.js versions | Explicit triggers | npm quality gates |\n| --- | --- | --- | --- |\n${rows}\n\n## Drift prevention\n\n\`npm run test:repo-contract\` fails when runtime sources disagree, an active workflow reintroduces an unsupported Node version/action major, the Node ${runtime.minimumNode} compatibility floor is no longer exercised, or this generated document is stale.\n`;
}

function validateContract(contract, root = ROOT) {
  const failures = [];
  const fail = message => failures.push(message);
  const { runtime } = contract;

  if (!Number.isInteger(runtime.minimumNode) || runtime.minimumNode < MINIMUM_SUPPORTED_NODE_FLOOR) {
    fail(`package.json must declare Node >=${MINIMUM_SUPPORTED_NODE_FLOOR}; got ${runtime.packageEngine || 'missing'}`);
  }
  if (!Number.isInteger(runtime.primaryNode) || runtime.primaryNode < runtime.minimumNode) {
    fail(`.nvmrc primary Node must be >= minimum Node ${runtime.minimumNode}; got ${runtime.primaryNode ?? 'missing'}`);
  }
  if (runtime.dockerNode !== runtime.primaryNode) {
    fail(`Dockerfile Node ${runtime.dockerNode ?? 'missing'} must match .nvmrc Node ${runtime.primaryNode ?? 'missing'}`);
  }

  for (const major of contract.githubActions.checkoutMajors) {
    if (major < ACTION_MINIMUMS.checkout) fail(`actions/checkout@v${major} is below supported floor v${ACTION_MINIMUMS.checkout}`);
  }
  for (const major of contract.githubActions.setupNodeMajors) {
    if (major < ACTION_MINIMUMS.setupNode) fail(`actions/setup-node@v${major} is below supported floor v${ACTION_MINIMUMS.setupNode}`);
  }
  if (contract.githubActions.checkoutMajors.length !== 1) fail(`active workflows must use one checkout major; found ${contract.githubActions.checkoutMajors.join(', ') || 'none'}`);
  if (contract.githubActions.setupNodeMajors.length !== 1) fail(`active workflows must use one setup-node major; found ${contract.githubActions.setupNodeMajors.join(', ') || 'none'}`);

  for (const workflow of Object.values(contract.workflows)) {
    for (const node of workflow.nodeVersions) {
      if (node < runtime.minimumNode) fail(`${workflow.file} uses Node ${node}, below minimum ${runtime.minimumNode}`);
    }
  }

  if (!contract.ci) fail('ci.yml is missing');
  else {
    if (!contract.ci.nodeVersions.includes(runtime.primaryNode)) fail(`ci.yml must exercise primary Node ${runtime.primaryNode}`);
    if (!contract.ci.nodeVersions.includes(runtime.minimumNode)) fail(`ci.yml must exercise minimum supported Node ${runtime.minimumNode}`);
  }
  if (!contract.behavioralEvals) fail('behavioral-evals.yml is missing');
  else {
    if (!contract.behavioralEvals.scheduled) fail('behavioral-evals.yml must retain its scheduled trigger');
    if (!contract.behavioralEvals.nodeVersions.includes(runtime.primaryNode)) fail(`behavioral-evals.yml must use primary Node ${runtime.primaryNode}`);
  }
  if (!contract.release) fail('release.yml is missing');
  else if (!contract.release.nodeVersions.includes(runtime.primaryNode)) {
    fail(`release.yml must use primary Node ${runtime.primaryNode}`);
  }

  const generatedPath = path.join(root, 'docs', 'repository-contract.md');
  if (!fs.existsSync(generatedPath)) {
    fail('docs/repository-contract.md is missing; run npm run docs:sync');
  } else {
    const actual = fs.readFileSync(generatedPath, 'utf8').replace(/\r\n/g, '\n');
    const expected = renderContractMarkdown(contract).replace(/\r\n/g, '\n');
    if (actual !== expected) fail('docs/repository-contract.md is stale; run npm run docs:sync');
  }

  return failures;
}

function printSummary(contract) {
  console.log(`Node: >=${contract.runtime.minimumNode} supported; ${contract.runtime.primaryNode} primary; ${contract.runtime.dockerNode} Docker`);
  console.log(`Actions: checkout ${contract.githubActions.checkoutMajors.map(v => `v${v}`).join(', ')}; setup-node ${contract.githubActions.setupNodeMajors.map(v => `v${v}`).join(', ')}`);
  for (const workflow of Object.values(contract.workflows)) {
    console.log(`${workflow.file}: Node ${workflow.nodeVersions.join(', ') || 'n/a'}; gates ${workflow.qualityGates.join(', ') || 'n/a'}`);
  }
}

if (require.main === module) {
  const args = new Set(process.argv.slice(2));
  const contract = collectContract();
  if (args.has('--json')) {
    process.stdout.write(`${JSON.stringify(contract, null, 2)}\n`);
  } else if (args.has('--check')) {
    const failures = validateContract(contract);
    if (failures.length) {
      for (const failure of failures) console.error(`❌ ${failure}`);
      process.exitCode = 1;
    } else {
      console.log('✅ Repository runtime/workflow contract is consistent.');
    }
  } else {
    printSummary(contract);
  }
}

module.exports = {
  ACTION_MINIMUMS,
  MINIMUM_SUPPORTED_NODE_FLOOR,
  collectContract,
  renderContractMarkdown,
  validateContract,
};
