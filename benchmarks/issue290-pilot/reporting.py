"""Metric-specific denominators and deterministic descriptive pairs."""
from collections import defaultdict


def quality_included(row):
    return not row.get('preflight') and (row.get('classification') != 'inconclusive' or row.get('budget_failure'))


def summarize_groups(rows):
    groups = defaultdict(list)
    for row in rows:
        groups[(row['series'], row['model']['engine'], row['workload'], row['arm'])].append(row)
    result = []
    for key, group in sorted(groups.items()):
        included = [row for row in group if quality_included(row)]
        record = dict(zip(('series', 'engine', 'workload', 'arm'), key))
        record.update(n_attempted=len(group), n_quality_included=len(included),
                      n_quality_excluded=len(group)-len(included),
                      artifact_passes=sum(bool(r['independent_grader'].get('pass')) and not r.get('budget_failure') for r in included),
                      budget_failures=sum(bool(r.get('budget_failure')) for r in included))
        for output, field in [('reference_bytes', 'reference_returned_bytes'),
                              ('exact_reference_bytes_lower_bound', 'exact_reference_bytes_lower_bound'),
                              ('mean_wall_seconds', 'wall_seconds'),
                              ('api_equivalent_cost_usd', 'api_equivalent_cost_usd'),
                              ('api_equivalent_input_cost_usd', 'api_equivalent_input_cost_usd')]:
            known = [r[field] for r in included if r.get(field) is not None]
            record['n_'+output+'_included'] = len(known)
            record['n_'+output+'_excluded'] = len(group)-len(known)
            # Missing data never becomes zero. A known subtotal is explicitly
            # different from an unknown group total.
            record[output+'_known_subtotal'] = sum(known) if known else None
            record[output] = (sum(known)/len(known) if output.startswith('mean_') else sum(known)) if known and len(known) == len(included) else None
        result.append(record)
    return result


def paired_rows(rows):
    cells = defaultdict(dict)
    for row in rows:
        if quality_included(row):
            key = (row['series'], row['model']['engine'], row['workload'], row['repeat'])
            if row['arm'] in cells[key]:
                raise ValueError('duplicate arm in paired cell')
            cells[key][row['arm']] = row
    pairs = []
    for key, arms in sorted(cells.items()):
        pair = dict(zip(('series', 'engine', 'workload', 'repeat'), key))
        for field in ('reference_returned_bytes', 'api_equivalent_input_cost_usd', 'api_equivalent_cost_usd', 'wall_seconds'):
            a, b = (arms.get(arm, {}).get(field) for arm in ('A', 'B'))
            known = a is not None and b is not None
            pair[field] = {'included': known, 'A': a, 'B': b,
                           'delta_percent': (b-a)/a*100 if known and a else None}
        pairs.append(pair)
    return pairs


def report_tables(rows, pairs):
    lines = ['<!-- Generated by replay.py; parent-stream content attribution only. -->',
             '| Family | Model | Pass / quality n | Excluded attempts |',
             '|---|---|---:|---:|']
    families = defaultdict(list)
    for row in rows:
        if not row.get('preflight'):
            name = 'True Fable' if 'fable' in row['series'] else row['workload']
            families[(name, row['model']['engine'])].append(row)
    for (name, engine), group in sorted(families.items()):
        included = [r for r in group if quality_included(r)]
        passes = sum(bool(r['independent_grader'].get('pass')) and not r.get('budget_failure') for r in included)
        lines.append(f'| {name} | {engine} | {passes}/{len(included)} | {len(group)-len(included)} |')
    for field, title, precision in [('reference_returned_bytes', 'Attributable reference bytes (lower bound)', 0),
                                    ('api_equivalent_input_cost_usd', 'List-price input cost (frozen telemetry)', 6)]:
        lines.extend(['', '### '+title, '', '| Family | Model | Included / candidate pairs | A | B | Delta |', '|---|---|---:|---:|---:|---:|'])
        grouped = defaultdict(list)
        for pair in pairs:
            name = 'True Fable' if 'fable' in pair['series'] else pair['workload']
            grouped[(name, pair['engine'])].append(pair[field])
        for (name, engine), group in sorted(grouped.items()):
            known = [p for p in group if p['included']]
            a, b = (sum(p[arm] for p in known) for arm in ('A', 'B'))
            values = [f'{a:.{precision}f}', f'{b:.{precision}f}', f'{(b-a)/a*100:+.1f}%' if a else 'unknown'] if known else ['unknown']*3
            lines.append(f'| {name} | {engine} | {len(known)}/{len(group)} | '+ ' | '.join(values)+' |')
    return '\n'.join(lines)+'\n'
